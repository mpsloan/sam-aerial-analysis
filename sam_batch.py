import numpy as np
import matplotlib.pyplot as plt
import cv2
import sys
import random
from segment_anything import SamAutomaticMaskGenerator
from segment_anything import sam_model_registry

random.seed(42)
image = cv2.imread('../validation_dataset/images_v1/P1483.png')
image = cv2.cvtColor(image, cv2.COLOR_BGR2RGB)

sys.path.append("..")

sam_checkpoint = "../segment-anything/sam_vit_h_4b8939.pth"
model_type = "vit_h"

device = "mps"

sam = sam_model_registry[model_type](checkpoint=sam_checkpoint)
sam.to(device=device)

mask_generator = SamAutomaticMaskGenerator(sam)
masks = mask_generator.generate(image)

# Visualizes all masks generated by SAM as a single color-coded overlay.
# Each detected object is assigned a random semi-transparent color and
# layered onto the original image, with larger objects drawn first so
# smaller objects remain visible on top. Used here to qualitatively
# inspect SAM's automatic mask generation output on aerial imagery.
def show_anns(anns):
    if len(anns) == 0:
        return
    sorted_anns = sorted(anns, key=(lambda x: x['area']), reverse=True)
    ax = plt.gca()
    ax.set_autoscale_on(False)

    img = np.ones((sorted_anns[0]['segmentation'].shape[0], sorted_anns[0]['segmentation'].shape[1], 4))
    img[:, :, 3] = 0
    for ann in sorted_anns:
        m = ann['segmentation']
        color_mask = np.concatenate([np.random.random(3), [0.35]])
        img[m] = color_mask
    ax.imshow(img)


# Visualize the number of masks and how they map to the image
print(len(masks))

plt.figure(figsize=(10,10))
plt.imshow(image)
show_anns(masks)
plt.axis('off')
plt.show()
